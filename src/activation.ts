/**
 * "Linking" an account = pointing CLAUDE_CONFIG_DIR at its folder for:
 *   1. new integrated terminals          (EnvironmentVariableCollection)
 *   2. new chats of the Claude Code ext   (claudeCode.environmentVariables)
 *   3. shells outside VS Code (opt-in)    (<root>/env.sh | env.fish | env.ps1 | active)
 * "Unlinking" = back to the default ~/.claude (variable removed).
 */
import * as path from 'path';
import * as vscode from 'vscode';
import { Profile } from './store';
import { writeFileAtomic } from './util';

interface EnvEntry {
  name: string;
  value: string;
}

export const CLAUDE_CODE_EXTENSION_ID = 'anthropic.claude-code';

const cfg = () => vscode.workspace.getConfiguration('claudeSwitch');

export function claudeCodeSettingAvailable(): boolean {
  const info = vscode.workspace.getConfiguration('claudeCode').inspect<EnvEntry[]>('environmentVariables');
  return info?.defaultValue !== undefined;
}

/** CLAUDE_CONFIG_DIR currently set for the Claude Code extension (user settings), if any. */
export function claudeCodeConfigDir(): string | undefined {
  const info = vscode.workspace.getConfiguration('claudeCode').inspect<EnvEntry[]>('environmentVariables');
  const list = Array.isArray(info?.globalValue) ? info.globalValue : [];
  const hit = list.find((e) => e && e.name === 'CLAUDE_CONFIG_DIR' && typeof e.value === 'string' && e.value.trim());
  return hit?.value;
}

export class Activator {
  constructor(
    private readonly ctx: vscode.ExtensionContext,
    private readonly root: string,
    private readonly log: vscode.OutputChannel,
  ) {}

  async apply(p: Profile): Promise<void> {
    this.applyTerminals(p);
    if (cfg().get<boolean>('syncClaudeCodeExtension', true)) {
      try {
        await this.applyClaudeCodeSetting(p);
      } catch (e) {
        this.log.appendLine(`[activate] could not update claudeCode.environmentVariables: ${(e as Error).message}`);
      }
    }
    if (cfg().get<boolean>('writeShellEnvFiles', true)) {
      try {
        this.writeShellFiles(p);
      } catch (e) {
        this.log.appendLine(`[activate] could not write shell env files: ${(e as Error).message}`);
      }
    }
  }

  private applyTerminals(p: Profile): void {
    const coll = this.ctx.environmentVariableCollection;
    coll.persistent = true;
    coll.clear();
    if (p.isDefault || !cfg().get<boolean>('applyToTerminals', true)) {
      coll.description = undefined;
      return;
    }
    coll.replace('CLAUDE_CONFIG_DIR', p.configDir);
    coll.description = `Claude account “${p.name}” (CLAUDE_CONFIG_DIR=${p.configDir})`;
  }

  private async applyClaudeCodeSetting(p: Profile): Promise<void> {
    if (!claudeCodeSettingAvailable()) return; // official extension not installed / disabled
    const conf = vscode.workspace.getConfiguration('claudeCode');
    const info = conf.inspect<EnvEntry[]>('environmentVariables');
    const current = Array.isArray(info?.globalValue) ? info.globalValue : [];
    const next = current.filter((e) => !(e && e.name === 'CLAUDE_CONFIG_DIR'));
    if (!p.isDefault) next.push({ name: 'CLAUDE_CONFIG_DIR', value: p.configDir });
    if (JSON.stringify(next) === JSON.stringify(current)) return;
    await conf.update('environmentVariables', next.length ? next : undefined, vscode.ConfigurationTarget.Global);
    this.log.appendLine(`[activate] claudeCode.environmentVariables → ${p.isDefault ? '(CLAUDE_CONFIG_DIR removed)' : p.configDir}`);
  }

  private writeShellFiles(p: Profile): void {
    const header = `Generated by Claude Account Switch — active account: ${p.name}. Do not edit.`;
    const dir = p.configDir;
    const sq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;
    const fq = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
    const pq = (s: string) => `'${s.replace(/'/g, "''")}'`;

    const sh = p.isDefault
      ? `# ${header}\nif [ -z "\${CLAUDE_SWITCH_PINNED:-}" ]; then\n  unset CLAUDE_CONFIG_DIR\nfi\n`
      : `# ${header}\nif [ -z "\${CLAUDE_SWITCH_PINNED:-}" ]; then\n  export CLAUDE_CONFIG_DIR=${sq(dir)}\nfi\n`;
    const fish = p.isDefault
      ? `# ${header}\nif not set -q CLAUDE_SWITCH_PINNED\n  set -e CLAUDE_CONFIG_DIR\nend\n`
      : `# ${header}\nif not set -q CLAUDE_SWITCH_PINNED\n  set -gx CLAUDE_CONFIG_DIR ${fq(dir)}\nend\n`;
    const ps1 = p.isDefault
      ? `# ${header}\nif (-not $env:CLAUDE_SWITCH_PINNED) { Remove-Item Env:CLAUDE_CONFIG_DIR -ErrorAction SilentlyContinue }\n`
      : `# ${header}\nif (-not $env:CLAUDE_SWITCH_PINNED) { $env:CLAUDE_CONFIG_DIR = ${pq(dir)} }\n`;

    writeFileAtomic(path.join(this.root, 'env.sh'), sh, 0o644);
    writeFileAtomic(path.join(this.root, 'env.fish'), fish, 0o644);
    writeFileAtomic(path.join(this.root, 'env.ps1'), ps1, 0o644);
    writeFileAtomic(path.join(this.root, 'active'), p.isDefault ? '' : `${dir}\n`, 0o644);
  }
}
